import assert from 'node:assert/strict';
import { isValue, isMe, isToday, isRecommendations, workspaceId, cursor } from '../lib/pilot-contract.ts';
import { formatAmount } from '../lib/value.ts';
const fact = { amount:'9007199254740993.01', unit:'rub', source:'yandex_direct', period:{from:'2026-10-01',to:'2026-10-07'}, calculation_type:'actual', data_status:'complete', data_sufficiency:'sufficient', rule_version:null, formula:null, unavailable_reason:null };
assert(isValue(fact));
assert.equal(formatAmount(fact.amount,'rub'),'9 007 199 254 740 993,01 ₽');
assert(!isValue({...fact,amount:123.45}));
assert(!isValue({...fact,calculation_type:'estimated'}));
assert(isValue({...fact,calculation_type:'estimated',formula:'sum(cost)',data_status:'partial'}));
const missing = {...fact,amount:null,calculation_type:'unavailable',data_sufficiency:'insufficient',unavailable_reason:'no_data'};
assert(isValue(missing));
assert(!isValue({...missing,amount:'0.00'}));
assert(!isValue({...fact,period:{from:'2026-10-07',to:'2026-10-01'}}));
assert(!isValue({...fact,source:'unknown'}));
assert(!isValue({...fact,unit:['rub']}));
assert(!isValue({...fact,data_status:['complete']}));
assert(!isValue({...missing,unavailable_reason:['no_data']}));
assert(!isValue({...fact,period:{from:'2026-02-31',to:'2026-03-01'}}));
assert(isMe({organizations:[{name:'Agency',workspaces:[{id:'ws_1',name:'Client'}]}]}));
assert(!isMe({organizations:[{name:'Agency',workspaces:[{id:'../secret',name:'Client'}]}]}));
assert(!workspaceId('ws_1/../../me')); assert(!cursor('o0&url=https://example.com')); assert(cursor('o50'));
const freshness = {status:null,data_to:null,last_success_at:null};
const today = {spent:missing,exposure:{total:missing},counts:{active:0},last_audit_at:null,data_status:'complete',data_freshness:{yandex_direct:freshness,yandex_metrika:freshness}};
assert(isToday(today)); assert(!isToday({...today,counts:{active:-1}}));
assert(!isToday({...today,data_freshness:{yandex_direct:{...freshness,data_to:'wrong'},yandex_metrika:freshness}}));
assert(isRecommendations({items:[],next_cursor:null}));
const rec = {id:'rec_1',version_id:'rv_1',computed_at:'2026-10-07T12:00:00Z',title:'Review',action_level:'review',exposure:fact,exposure_overlap:fact};
assert(isRecommendations({items:[rec],next_cursor:'o50'}));
assert(!isRecommendations({items:[{...rec,computed_at:null}],next_cursor:null}));
assert(!isRecommendations({items:[{...rec,action_level:['change']}],next_cursor:null}));
console.log('PASS: pilot Value boundaries, Decimal precision, workspace/cursor IDs, freshness and list-only contract.');
