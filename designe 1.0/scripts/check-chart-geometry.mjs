import assert from 'node:assert/strict';
import {budgetBars,leadShares} from '../lib/chart-geometry.ts';
import {pointExtrema} from '../components/ix/geometry.ts';
assert.equal(pointExtrema([{value:null},{value:NaN},{value:Infinity}]),null);
const zero={value:0}, negative={value:-2}, high={value:9};
assert.deepEqual(pointExtrema([zero,negative,high]),{min:negative,max:high});
assert.deepEqual(pointExtrema([zero]),{min:zero,max:zero});
const exactLow={value:9007199254740992,evidence:{amount:'9007199254740992.01'}};
const exactHigh={value:9007199254740992,evidence:{amount:'9007199254740992.02'}};
assert.deepEqual(pointExtrema([exactHigh,exactLow]),{min:exactLow,max:exactHigh});
const fractionLow={value:-0.2,evidence:{amount:'-0.20'}},fractionHigh={value:0.02,evidence:{amount:'0.020'}};
assert.deepEqual(pointExtrema([fractionHigh,fractionLow]),{min:fractionLow,max:fractionHigh});
console.log('PASS chart extrema: gaps, nonfinite, zero, negative, single point, exact Decimal order');
assert.deepEqual(budgetBars('50.00','100'),[50,100]);
assert.deepEqual(budgetBars('200','100.000'),[100,50]);
assert.deepEqual(budgetBars('0','0.00'),[0,0]);
assert.deepEqual(budgetBars('9007199254740993.01','9007199254740993.01'),[100,100]);
for(const value of ['-1','NaN','Infinity','1e5','1.2.3'])assert.equal(budgetBars(value,'1'),null);
console.log('PASS chart geometry: exact Decimal scaling, zero, large amounts, invalid inputs');
assert.deepEqual(leadShares({total:100,qualified:60,unresolved:25}),[60,25,15]);
assert.deepEqual(leadShares({total:4,qualified:4,unresolved:0}),[100,0,0]);
for(const counts of [{total:0,qualified:0,unresolved:0},{total:2,qualified:2,unresolved:1},{total:3,qualified:-1,unresolved:0},{total:3,qualified:1.5,unresolved:0}])assert.equal(leadShares(counts),null);
console.log('PASS lead distribution: exhaustive partition, zero, invalid and overlapping counts');
